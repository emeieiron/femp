const EDITOR_HEADER: &str = "// Generated by femp. Do not edit.\n";

pub struct StagedProject {
    pub project: Project,
    _directory: tempfile::TempDir,
}

/// Each invocation compiles an isolated set of ingots with the generated
/// sources in their normal module paths. Platform artifacts still use the
/// original project's build and dist directories.
pub fn stage(
    project: &Project,
    platforms: &[&dyn Platform],
    include_shared: bool,
) -> Result<Option<StagedProject>> {
    let mut pending: Vec<_> = project
        .modules
        .iter()
        .filter(|module| {
            (include_shared && module.is_shared())
                || platforms
                    .iter()
                    .any(|platform| module.platform() == Some(platform.id()))
        })
        .collect();
    let mut selected = BTreeSet::new();
    while let Some(module) = pending.pop() {
        if selected.insert(module.name.as_str()) {
            pending.extend(project.dependencies_of(module));
        }
    }
    let originals: Vec<_> = project
        .modules
        .iter()
        .filter(|module| selected.contains(module.name.as_str()))
        .collect();
    if originals
        .iter()
        .all(|module| project.manifest.modules[&module.name].generate.is_empty())
    {
        return Ok(None);
    }

    let build = project.root.join(BUILD_DIR);
    fs::create_dir_all(&build).with_context(|| format!("cannot create {}", build.display()))?;
    let directory = tempfile::Builder::new()
        .prefix(".sources-")
        .tempdir_in(&build)
        .context("cannot create a source staging directory")?;
    let root = directory
        .path()
        .canonicalize()
        .context("cannot resolve source staging directory")?;
    let dirs: BTreeMap<_, _> = originals
        .iter()
        .map(|module| (module.name.as_str(), root.join(&module.name)))
        .collect();
    stage_workspace(project, &root, &dirs)?;

    let mut staged = project.clone();
    staged
        .modules
        .retain(|module| selected.contains(module.name.as_str()));
    for (original, module) in originals.iter().zip(&mut staged.modules) {
        module.dir.clone_from(&dirs[original.name.as_str()]);
        copy_sources(&original.dir.join(SOURCE_DIR), &module.dir.join(SOURCE_DIR))?;
        stage_ingot(project, original, &module.dir, &dirs)?;
        module.ingot = IngotManifest::read(&module.dir)?;
    }

    let mut refresh = Vec::new();
    for (original, module) in originals.iter().zip(&staged.modules) {
        for (name, generator) in &project.manifest.modules[&module.name].generate {
            let editor = original.dir.join(&generator.output);
            let exists = validate_editor_output(&editor)?;
            let source = generate(project, original, name, generator)?;
            write_file(&module.dir.join(&generator.output), &source)?;
            if exists {
                refresh.push((editor, editor_copy(&source)));
            }
        }
    }
    for (path, source) in refresh {
        write_editor_output(&path, &source)?;
    }

    Ok(Some(StagedProject {
        project: staged,
        _directory: directory,
    }))
}

fn stage_workspace(project: &Project, root: &Path, dirs: &BTreeMap<&str, PathBuf>) -> Result<()> {
    let mut document = Table::new();
    for directory in project.root.ancestors() {
        let source = directory.join(INGOT_FILE);
        if source.is_file() {
            let original: Table = fs::read_to_string(&source)?
                .parse()
                .with_context(|| format!("cannot read {}", source.display()))?;
            if original.contains_key("workspace") || original.contains_key("members") {
                document = original;
                remap_workspace_dependencies(&mut document, directory, project, root, dirs)?;
                break;
            }
        }
    }

    // Fe also accepts top-level workspace keys. Replace membership in either form.
    for key in ["members", "default-members", "exclude"] {
        document.remove(key);
    }
    let workspace = document
        .entry("workspace".to_string())
        .or_insert(Value::Table(Table::new()))
        .as_table_mut()
        .context("Fe workspace must be a table")?;
    for (key, default) in [("name", project.name()), ("version", project.version())] {
        workspace
            .entry(key.to_string())
            .or_insert(Value::String(default.to_string()));
    }
    workspace.remove("default-members");
    workspace.remove("exclude");
    workspace.insert(
        "members".into(),
        Value::Array(
            dirs.keys()
                .map(|name| Value::String((*name).into()))
                .collect(),
        ),
    );
    write_file(&root.join(INGOT_FILE), toml::to_string(&document)?)?;
    Ok(())
}

fn remap_workspace_dependencies(
    document: &mut Table,
    original: &Path,
    project: &Project,
    root: &Path,
    dirs: &BTreeMap<&str, PathBuf>,
) -> Result<()> {
    let Some(dependencies) = document
        .get_mut("dependencies")
        .and_then(Value::as_table_mut)
    else {
        return Ok(());
    };
    for (_, dependency) in dependencies.iter_mut() {
        let path = match dependency {
            Value::String(text) if !femp_core::naming::looks_like_version(text) => {
                Some(text.as_str())
            }
            Value::Table(table) if !table.contains_key("source") => {
                table.get("path").and_then(Value::as_str)
            }
            _ => None,
        };
        if let Some(path) = path {
            let original_path = original.join(path);
            let canonical = original_path.canonicalize().unwrap_or(original_path);
            let target = project
                .modules
                .iter()
                .find(|module| module.dir == canonical)
                .and_then(|module| dirs.get(module.name.as_str()))
                .unwrap_or(&canonical);
            rewrite_dependency(dependency, relative_path(root, target)?);
        }
    }
    Ok(())
}

fn copy_sources(from: &Path, to: &Path) -> Result<()> {
    fs::create_dir_all(to).with_context(|| format!("cannot create {}", to.display()))?;
    let entries = match fs::read_dir(from) {
        Ok(entries) => entries,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(error).with_context(|| format!("cannot read {}", from.display())),
    };
    for entry in entries {
        let entry = entry?;
        let path = entry.path();
        let target = to.join(entry.file_name());
        if entry.file_type()?.is_dir() {
            copy_sources(&path, &target)?;
        } else if path.is_file() {
            copy_file(&path, &target)?;
        }
    }
    Ok(())
}

fn stage_ingot(
    project: &Project,
    original: &Module,
    destination: &Path,
    dirs: &BTreeMap<&str, PathBuf>,
) -> Result<()> {
    let path = original.dir.join(INGOT_FILE);
    let mut document: Table = fs::read_to_string(&path)?
        .parse()
        .with_context(|| format!("cannot read {}", path.display()))?;
    if let Some(dependencies) = document
        .get_mut("dependencies")
        .and_then(Value::as_table_mut)
    {
        let workspace = Workspace::discover(&original.dir)?;
        for dependency in &original.ingot.dependencies {
            let target = match &dependency.source {
                DependencySource::Path(path) => {
                    match project.resolve_dependency(original, dependency) {
                        Some(module) => dirs
                            .get(module.name.as_str())
                            .unwrap_or(&module.dir)
                            .clone(),
                        None => original.dir.join(path).canonicalize().with_context(|| {
                            format!(
                                "cannot resolve dependency {} from {}",
                                dependency.alias,
                                original.dir.display()
                            )
                        })?,
                    }
                }
                DependencySource::Name(name) => {
                    let Some(workspace) = &workspace else {
                        continue;
                    };
                    if workspace
                        .dependencies
                        .iter()
                        .any(|item| item.alias == dependency.alias)
                    {
                        continue; // The staged workspace already carries this dependency.
                    }
                    let Some(target) = workspace.members.get(name) else {
                        continue;
                    };
                    if project.modules.iter().any(|module| {
                        &module.dir == target && dirs.contains_key(module.name.as_str())
                    }) {
                        continue; // The selected member is included in the staged workspace.
                    }
                    target.clone()
                }
                DependencySource::Remote(_) => continue,
            };
            let path = relative_path(destination, &target)?;
            let value = dependencies
                .get_mut(&dependency.alias)
                .context("dependency is missing from the ingot manifest")?;
            if matches!(dependency.source, DependencySource::Name(_)) && !value.is_table() {
                let mut table = Table::new();
                if let Some(version) = value.as_str() {
                    table.insert("version".into(), Value::String(version.to_string()));
                }
                *value = Value::Table(table);
            }
            rewrite_dependency(value, path);
        }
    }
    write_file(&destination.join(INGOT_FILE), toml::to_string(&document)?)?;
    Ok(())
}

fn rewrite_dependency(value: &mut Value, path: String) {
    if let Some(table) = value.as_table_mut() {
        table.insert("path".into(), Value::String(path));
    } else {
        *value = Value::String(path);
    }
}

fn relative_path(from: &Path, to: &Path) -> Result<String> {
    let mut common = from;
    let mut result = PathBuf::new();
    while !to.starts_with(common) {
        common = common.parent().with_context(|| {
            format!("cannot reference {} from {}", to.display(), from.display())
        })?;
        result.push("..");
    }
    result.push(to.strip_prefix(common)?);
    if result.as_os_str().is_empty() {
        return Ok(".".into());
    }
    let path = result.to_str().context("Fe dependency path is not UTF-8")?;
    Ok(if cfg!(windows) {
        path.replace('\\', "/")
    } else {
        path.to_owned()
    })
}

fn generate(
    project: &Project,
    original: &Module,
    name: &str,
    generator: &GeneratorSection,
) -> Result<String> {
    run_generator(project, original, name, generator)
        .with_context(|| format!("generation failed for {}.{name}", original.name))
}

/// Runs a generator under the FSGP v1 contract (docs/source-generators.md).
fn run_generator(
    project: &Project,
    original: &Module,
    name: &str,
    generator: &GeneratorSection,
) -> Result<String> {
    let mut command = Command::new(executable(original, generator));
    command
        .args(&generator.command[1..])
        .current_dir(&original.dir)
        .stdin(Stdio::null());

    console::step("Generating", &format!("{} / {name}", original.name));
    let result = command
        .output()
        .with_context(|| format!("could not run {}", describe(&command)))?;
    let diagnostics = locate_diagnostics(&String::from_utf8_lossy(&result.stderr), &original.dir, &project.root);
    if !result.status.success() {
        bail!(
            "{} exited with {}\n{}",
            describe(&command),
            result.status,
            diagnostics.trim_end()
        );
    }
    if !diagnostics.trim().is_empty() {
        console::warning(diagnostics.trim_end());
    }
    String::from_utf8(result.stdout).context("generator output must be UTF-8 Fe source")
}

/// Rewrites diagnostics of the form `path:line:column: message`, whose paths a generator
/// gives relative to its module, so each path resolves from the project root.
fn locate_diagnostics(diagnostics: &str, module: &Path, root: &Path) -> String {
    diagnostics
        .lines()
        .map(|line| locate_line(line, module, root).unwrap_or_else(|| line.to_string()))
        .collect::<Vec<_>>()
        .join("\n")
}

fn locate_line(line: &str, module: &Path, root: &Path) -> Option<String> {
    let (path, rest) = line.split_once(':')?;
    let mut parts = rest.splitn(3, ':');
    let (row, column, message) = (parts.next()?, parts.next()?, parts.next()?);
    let number = |text: &str| !text.is_empty() && text.bytes().all(|byte| byte.is_ascii_digit());
    if path.is_empty()
        || path.trim() != path
        || Path::new(path).is_absolute()
        || !number(row)
        || !number(column)
        || !message.starts_with(' ')
    {
        return None;
    }
    let path = console::relative(&module.join(path), root);
    Some(format!("{path}:{row}:{column}:{message}"))
}

pub fn editor_sources(project: &Project) -> Result<()> {
    let mut outputs = Vec::new();
    for module in &project.modules {
        for (name, generator) in &project.manifest.modules[&module.name].generate {
            let path = module.dir.join(&generator.output);
            validate_editor_output(&path)?;
            outputs.push((path, editor_copy(&generate(project, module, name, generator)?)));
        }
    }
    for (path, source) in outputs {
        write_editor_output(&path, &source)?;
        console::step("Generated", &console::relative(&path, &project.root));
    }
    Ok(())
}

fn editor_copy(source: &str) -> String {
    format!("{EDITOR_HEADER}{source}")
}

fn validate_editor_output(path: &Path) -> Result<bool> {
    match fs::symlink_metadata(path) {
        Ok(metadata)
            if metadata.is_file() && fs::read(path)?.starts_with(EDITOR_HEADER.as_bytes()) =>
        {
            Ok(true)
        }
        Ok(_) => bail!("output {} would replace an existing source", path.display()),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(false),
        Err(error) => Err(error).with_context(|| format!("cannot read {}", path.display())),
    }
}

fn write_editor_output(path: &Path, source: &str) -> Result<()> {
    let exists = validate_editor_output(path)?;
    if exists && fs::read(path)? == source.as_bytes() {
        return Ok(());
    }
    let parent = path
        .parent()
        .context("generated source must have a parent directory")?;
    fs::create_dir_all(parent)?;
    let mut temporary = tempfile::NamedTempFile::new_in(parent)?;
    temporary.write_all(source.as_bytes())?;
    if exists {
        temporary.persist(path)
    } else {
        temporary.persist_noclobber(path)
    }
    .with_context(|| format!("cannot write {}", path.display()))?;
    Ok(())
}

pub fn executable(original: &Module, generator: &GeneratorSection) -> PathBuf {
    let program = Path::new(&generator.command[0]);
    if program.is_relative() && program.components().count() > 1 {
        original.dir.join(program)
    } else {
        program.to_path_buf()
    }
}

pub fn available(program: &Path) -> bool {
    if program.is_absolute() {
        return is_executable(program);
    }
    env::var_os("PATH")
        .is_some_and(|paths| env::split_paths(&paths).any(|dir| is_executable(&dir.join(program))))
}

fn is_executable(path: &Path) -> bool {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        path.metadata()
            .is_ok_and(|meta| meta.is_file() && meta.permissions().mode() & 0o111 != 0)
    }
    #[cfg(windows)]
    {
        path.is_file()
            || env::var_os("PATHEXT").is_some_and(|extensions| {
                extensions.to_string_lossy().split(';').any(|extension| {
                    path.with_extension(extension.trim_start_matches('.'))
                        .is_file()
                })
            })
    }
    #[cfg(not(any(unix, windows)))]
    {
        path.is_file()
    }
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::locate_diagnostics;

    #[test]
    fn module_relative_diagnostics_resolve_from_the_project_root() {
        let root = Path::new("/work/app");
        let module = Path::new("/work/app/shared");
        let text = "src/models.fe:3:5: error: unsupported field\n\
                    note without a location\n\
                    /abs/models.fe:1:1: error: absolute\n\
                    src/a.fe:x:1: error: not a location";
        assert_eq!(
            locate_diagnostics(text, module, root),
            "shared/src/models.fe:3:5: error: unsupported field\n\
             note without a location\n\
             /abs/models.fe:1:1: error: absolute\n\
             src/a.fe:x:1: error: not a location"
        );
    }
}
