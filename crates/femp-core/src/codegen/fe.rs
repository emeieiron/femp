//! Helpers for generating Fe source, shared by the property harnesses.

use crate::property::{Param, Ty};

pub use super::typescript::SourceWriter;

pub const HEADER: &str = "// Generated by femp. Do not edit.";
const INDENT: &str = "    ";

pub fn writer() -> SourceWriter {
    SourceWriter::with_indent(INDENT)
}

/// The argument list of a call, labelled as each parameter requires.
pub fn arguments(params: &[Param], values: &[String]) -> String {
    params
        .iter()
        .zip(values)
        .map(|(param, value)| match &param.label {
            Some(label) => format!("{label}: {value}"),
            None => value.clone(),
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// The Fe spelling of a primitive type.
pub fn type_name(ty: Ty) -> String {
    ty.to_string()
}

/// Local names for generated arguments, which cannot clash with user code.
pub fn locals(count: usize) -> Vec<String> {
    (0..count).map(|index| format!("femp_arg{index}")).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn param(label: Option<&str>) -> Param {
        Param {
            name: "x".into(),
            label: label.map(str::to_string),
            ty: Ty::Uint(8),
            generator: "any".into(),
        }
    }

    #[test]
    fn labels_arguments_as_declared() {
        let params = [param(Some("total")), param(None), param(Some("at"))];
        assert_eq!(
            arguments(&params, &locals(3)),
            "total: femp_arg0, femp_arg1, at: femp_arg2"
        );
    }

    #[test]
    fn indents_with_four_spaces() {
        let mut out = writer();
        out.block("fn f() {", "}", |out| {
            out.line("x");
        });
        assert_eq!(out.finish(), "fn f() {\n    x\n}\n");
    }
}
