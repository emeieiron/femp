use std::path::{Component, Path, PathBuf};

use toml::{Table, Value};

use crate::artifact::{reset_dir, write_file};
use crate::error::Result;
use crate::ingot::{INGOT_FILE, IngotManifest, ROOT_SOURCE};
use crate::platform::PlatformId;
use crate::project::{Module, ModuleRole};

/// A generated ingot that exposes a suite's entry points on one platform.
pub struct HarnessIngot<'a> {
    pub name: &'a str,
    pub target: &'a str,
    pub dependencies: Vec<(String, PathBuf)>,
    pub source: String,
}

/// Writes the ingot into a fresh `dir` and returns it as a platform module,
/// ready for that platform's build.
pub fn write_harness_ingot(
    dir: &Path,
    platform: &PlatformId,
    ingot: &HarnessIngot<'_>,
) -> Result<Module> {
    reset_dir(dir)?;
    write_file(&dir.join(INGOT_FILE), manifest(dir, ingot))?;
    write_file(&dir.join(ROOT_SOURCE), &ingot.source)?;
    Ok(Module {
        name: ingot.name.to_string(),
        dir: dir.to_path_buf(),
        source_dir: dir.to_path_buf(),
        ingot: IngotManifest::read(dir)?,
        role: ModuleRole::Platform(platform.clone()),
    })
}

fn manifest(dir: &Path, ingot: &HarnessIngot<'_>) -> String {
    let mut section = Table::new();
    section.insert("name".into(), Value::String(ingot.name.to_string()));
    section.insert("version".into(), Value::String("0.0.0".into()));
    section.insert("target".into(), Value::String(ingot.target.to_string()));
    let dependencies: Table = ingot
        .dependencies
        .iter()
        .map(|(alias, path)| {
            let path = relative(dir, path);
            (
                alias.clone(),
                Value::String(path.to_string_lossy().replace('\\', "/")),
            )
        })
        .collect();
    let mut document = Table::new();
    document.insert("ingot".into(), Value::Table(section));
    document.insert("dependencies".into(), Value::Table(dependencies));
    format!("# Generated by femp. Do not edit.\n{document}")
}

// Fe only accepts relative dependency paths.
fn relative(from: &Path, to: &Path) -> PathBuf {
    let from = from.canonicalize().unwrap_or_else(|_| from.to_path_buf());
    let to = to.canonicalize().unwrap_or_else(|_| to.to_path_buf());
    let from: Vec<Component> = from.components().collect();
    let to: Vec<Component> = to.components().collect();
    let common = from.iter().zip(&to).take_while(|(a, b)| a == b).count();
    let mut path: PathBuf = from[common..]
        .iter()
        .map(|_| Component::ParentDir)
        .collect();
    path.extend(&to[common..]);
    if path.as_os_str().is_empty() {
        path.push(".");
    }
    path
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn writes_a_platform_module() {
        let dir = tempfile::tempdir().unwrap();
        let subject = dir.path().join("shared");
        std::fs::create_dir_all(&subject).unwrap();
        let module = write_harness_ingot(
            &dir.path().join("harness"),
            &PlatformId::new("native"),
            &HarnessIngot {
                name: "core_harness",
                target: "native",
                dependencies: vec![("vesting_core".to_string(), subject.clone())],
                source: "pub fn main() {}\n".to_string(),
            },
        )
        .unwrap();

        assert_eq!(module.ingot.name, "core_harness");
        assert_eq!(module.ingot.target.as_deref(), Some("native"));
        assert_eq!(module.ingot.dependencies[0].alias, "vesting_core");
        let manifest = std::fs::read_to_string(module.dir.join(INGOT_FILE)).unwrap();
        assert!(
            manifest.contains("vesting_core = \"../shared\""),
            "{manifest}"
        );
        assert_eq!(module.platform(), Some(&PlatformId::new("native")));
        assert_eq!(
            std::fs::read_to_string(module.root_source()).unwrap(),
            "pub fn main() {}\n"
        );
    }
}
