//! Fe 26.6 compiles a single source file to WebAssembly, not an ingot, so a
//! module and the project modules it depends on are merged into one file
//! before the compiler sees them. The module's own root stays the root of
//! that file (its public functions are the exports) and each dependency
//! becomes an inline module named after its ingot.

mod dependencies;
mod rewrite;

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use femp_core::Result;
use femp_core::ingot::SOURCE_DIR;
use femp_core::project::{Module, Project};
use femp_core::source_tree::ModuleTree;

use rewrite::rewrite_path_roots;

const INGOT_ROOT: &str = "ingot";

pub fn bundle(project: &Project, module: &Module) -> Result<String> {
    let graph = dependencies::graph(project, module)?;
    let root = &module.dir;
    let roots = BTreeMap::new();
    let root_tree = ModuleTree::read(&root.join(SOURCE_DIR))?;
    let mut used: BTreeSet<_> = root_tree.children.keys().cloned().collect();
    let mut mounts = roots;
    for (index, (dir, ingot)) in graph.iter().filter(|(dir, _)| *dir != root).enumerate() {
        let mut name = ingot.name.clone();
        // The mounted names are internal. Different revisions and authored modules
        // can legitimately expose the same ingot name.
        if !used.insert(name.clone()) {
            name = format!("_femp_dependency_{index}");
            while !used.insert(name.clone()) {
                name.push('_');
            }
        }
        mounts.insert(dir.clone(), name);
    }

    let mut bundled = format!(
        "// Generated by femp from module `{}`. Do not edit.\n",
        module.name
    );
    read_sources(root_tree, &graph[root], &mounts, None).render(&mut bundled);
    for (dir, mount) in &mounts {
        bundled.push_str(&format!("\npub mod {mount} {{\n"));
        let tree = ModuleTree::read(&dir.join(SOURCE_DIR))?;
        read_sources(tree, &graph[dir], &mounts, Some(mount)).render(&mut bundled);
        bundled.push_str("}\n");
    }
    Ok(bundled)
}

fn read_sources(
    mut tree: ModuleTree,
    ingot: &dependencies::Ingot,
    mounts: &BTreeMap<PathBuf, String>,
    mounted_at: Option<&str>,
) -> ModuleTree {
    let resolve = |word: &str| {
        if word == INGOT_ROOT {
            mounted_at.map(|mount| format!("{INGOT_ROOT}::{mount}"))
        } else {
            ingot
                .edges
                .get(word)
                .and_then(|path: &PathBuf| mounts.get(Path::new(path)))
                .map(|mount| format!("{INGOT_ROOT}::{mount}"))
        }
    };
    tree.map_sources(&|source| rewrite_path_roots(source, &resolve));
    tree
}

#[cfg(test)]
mod tests {
    use std::fs;
    use std::path::Path;

    use super::*;

    fn write(root: &Path, relative: &str, contents: &str) {
        let path = root.join(relative);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, contents).unwrap();
    }

    fn project(root: &Path, web_dependencies: &str) -> Project {
        write(
            root,
            "femp.toml",
            "[project]\nname = \"demo\"\nversion = \"0.1.0\"\n\n\
             [modules.core]\npath = \"shared\"\n\n\
             [modules.web]\npath = \"wasm\"\nplatform = \"wasm\"\n",
        );
        write(root, "shared/fe.toml", "[ingot]\nname = \"demo_core\"\n");
        write(root, "shared/src/lib.fe", "pub use math::double\n");
        write(
            root,
            "shared/src/math.fe",
            "use ingot::limits::MAX\n\npub fn double(_ x: u64) -> u64 {\n    x * 2\n}\n",
        );
        write(root, "shared/src/limits.fe", "pub const MAX: u64 = 10\n");
        write(
            root,
            "wasm/fe.toml",
            &format!(
                "[ingot]\nname = \"demo_web\"\ntarget = \"wasm\"\n\n[dependencies]\n{web_dependencies}\n"
            ),
        );
        write(
            root,
            "wasm/src/lib.fe",
            "use logic::double\n\npub fn twice(x: u64) -> u64 {\n    double(x)\n}\n",
        );
        Project::load(root).unwrap()
    }

    #[test]
    fn merges_a_module_with_its_dependencies() {
        let dir = tempfile::tempdir().unwrap();
        let project = project(dir.path(), "logic = \"../shared\"");
        let bundled = bundle(&project, project.module("web").unwrap()).unwrap();

        assert_eq!(
            bundled,
            "// Generated by femp from module `web`. Do not edit.\n\
             use ingot::demo_core::double\n\n\
             pub fn twice(x: u64) -> u64 {\n    double(x)\n}\n\n\
             pub mod demo_core {\n\
             pub use math::double\n\n\
             pub mod limits {\npub const MAX: u64 = 10\n}\n\n\
             pub mod math {\n\
             use ingot::demo_core::limits::MAX\n\n\
             pub fn double(_ x: u64) -> u64 {\n    x * 2\n}\n\
             }\n\
             }\n"
        );
    }

    #[test]
    fn reports_unresolved_dependencies() {
        let dir = tempfile::tempdir().unwrap();
        let project = project(dir.path(), "logic = \"../shared\"\nremote = \"1.2.3\"");
        let error = bundle(&project, project.module("web").unwrap()).unwrap_err();

        assert!(
            error
                .to_string()
                .contains("cannot resolve dependency remote"),
            "{error}"
        );
    }

    #[test]
    fn gives_dependencies_unique_mounts() {
        let dir = tempfile::tempdir().unwrap();
        let project = project(dir.path(), "logic = \"../shared\"");
        write(dir.path(), "wasm/src/demo_core.fe", "pub fn local() {}\n");
        let bundled = bundle(&project, project.module("web").unwrap()).unwrap();
        assert!(bundled.contains("use ingot::_femp_dependency_0::double"));
        assert!(bundled.contains("pub mod demo_core"));
    }
}
