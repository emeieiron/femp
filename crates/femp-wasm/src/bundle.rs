//! Fe 26.6 compiles a single source file to WebAssembly, not an ingot, so a
//! module and the project modules it depends on are merged into one file
//! before the compiler sees them. The module's own root stays the root of
//! that file (its public functions are the exports) and each dependency
//! becomes an inline module named after its ingot.

mod rewrite;
mod tree;

use std::collections::BTreeMap;

use femp_core::ingot::SOURCE_DIR;
use femp_core::project::{Module, Project};
use femp_core::{Error, Result};

use rewrite::rewrite_path_roots;
use tree::ModuleTree;

const INGOT_ROOT: &str = "ingot";

pub fn bundle(project: &Project, module: &Module) -> Result<String> {
    let dependencies = dependency_closure(project, module)?;

    let root = read_sources(project, module, None)?;
    if let Some(clash) = dependencies
        .iter()
        .find(|dependency| root.children.contains_key(&dependency.ingot.name))
    {
        return Err(Error::Artifact(format!(
            "module `{}` has its own `{}` module, which clashes with the dependency of that name",
            module.name, clash.ingot.name
        )));
    }

    let mut bundled = format!(
        "// Generated by femp from module `{}`. Do not edit.\n",
        module.name
    );
    root.render(&mut bundled);
    for dependency in dependencies {
        let name = &dependency.ingot.name;
        bundled.push_str(&format!("\npub mod {name} {{\n"));
        read_sources(project, dependency, Some(name))?.render(&mut bundled);
        bundled.push_str("}\n");
    }
    Ok(bundled)
}

fn dependency_closure<'a>(project: &'a Project, module: &'a Module) -> Result<Vec<&'a Module>> {
    let mut found: Vec<&Module> = Vec::new();
    let mut pending = vec![module];
    while let Some(current) = pending.pop() {
        for dependency in &current.ingot.dependencies {
            let target = project
                .resolve_dependency(current, dependency)
                .ok_or_else(|| {
                    Error::Artifact(format!(
                        "module `{}` depends on `{}`, which is not a module of this project; \
                         WebAssembly builds can only include project modules",
                        current.name, dependency.alias
                    ))
                })?;
            let is_new =
                target.name != module.name && found.iter().all(|known| known.name != target.name);
            if is_new {
                found.push(target);
                pending.push(target);
            }
        }
    }
    found.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(found)
}

// Inside the bundle a dependency is no longer a separate ingot, so paths
// that named it by its alias, and a dependency's own `ingot::` paths, must
// be redirected to the inline module that now holds its sources.
fn read_sources(
    project: &Project,
    module: &Module,
    mounted_at: Option<&str>,
) -> Result<ModuleTree> {
    let mut roots: BTreeMap<&str, String> = module
        .ingot
        .dependencies
        .iter()
        .filter_map(|dependency| {
            let target = project.resolve_dependency(module, dependency)?;
            Some((
                dependency.alias.as_str(),
                format!("{INGOT_ROOT}::{}", target.ingot.name),
            ))
        })
        .collect();
    if let Some(mount) = mounted_at {
        roots.insert(INGOT_ROOT, format!("{INGOT_ROOT}::{mount}"));
    }

    let mut tree = ModuleTree::read(&module.dir.join(SOURCE_DIR))?;
    tree.map_sources(&|source| rewrite_path_roots(source, &|word| roots.get(word).cloned()));
    Ok(tree)
}

#[cfg(test)]
mod tests {
    use std::fs;
    use std::path::Path;

    use super::*;

    fn write(root: &Path, relative: &str, contents: &str) {
        let path = root.join(relative);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, contents).unwrap();
    }

    fn project(root: &Path, web_dependencies: &str) -> Project {
        write(
            root,
            "femp.toml",
            "[project]\nname = \"demo\"\nversion = \"0.1.0\"\n\n\
             [modules.core]\npath = \"shared\"\n\n\
             [modules.web]\npath = \"wasm\"\nplatform = \"wasm\"\n",
        );
        write(root, "shared/fe.toml", "[ingot]\nname = \"demo_core\"\n");
        write(root, "shared/src/lib.fe", "pub use math::double\n");
        write(
            root,
            "shared/src/math.fe",
            "use ingot::limits::MAX\n\npub fn double(_ x: u64) -> u64 {\n    x * 2\n}\n",
        );
        write(root, "shared/src/limits.fe", "pub const MAX: u64 = 10\n");
        write(
            root,
            "wasm/fe.toml",
            &format!(
                "[ingot]\nname = \"demo_web\"\ntarget = \"wasm\"\n\n[dependencies]\n{web_dependencies}\n"
            ),
        );
        write(
            root,
            "wasm/src/lib.fe",
            "use logic::double\n\npub fn twice(x: u64) -> u64 {\n    double(x)\n}\n",
        );
        Project::load(root).unwrap()
    }

    #[test]
    fn merges_a_module_with_its_dependencies() {
        let dir = tempfile::tempdir().unwrap();
        let project = project(dir.path(), "logic = \"../shared\"");
        let bundled = bundle(&project, project.module("web").unwrap()).unwrap();

        assert_eq!(
            bundled,
            "// Generated by femp from module `web`. Do not edit.\n\
             use ingot::demo_core::double\n\n\
             pub fn twice(x: u64) -> u64 {\n    double(x)\n}\n\n\
             pub mod demo_core {\n\
             pub use math::double\n\n\
             pub mod limits {\npub const MAX: u64 = 10\n}\n\n\
             pub mod math {\n\
             use ingot::demo_core::limits::MAX\n\n\
             pub fn double(_ x: u64) -> u64 {\n    x * 2\n}\n\
             }\n\
             }\n"
        );
    }

    #[test]
    fn refuses_dependencies_from_outside_the_project() {
        let dir = tempfile::tempdir().unwrap();
        let project = project(dir.path(), "logic = \"../shared\"\nremote = \"1.2.3\"");
        let error = bundle(&project, project.module("web").unwrap()).unwrap_err();

        assert!(
            error
                .to_string()
                .contains("depends on `remote`, which is not a module of this project"),
            "{error}"
        );
    }

    #[test]
    fn refuses_a_module_that_shadows_a_dependency() {
        let dir = tempfile::tempdir().unwrap();
        let project = project(dir.path(), "logic = \"../shared\"");
        write(dir.path(), "wasm/src/demo_core.fe", "pub fn local() {}\n");
        let error = bundle(&project, project.module("web").unwrap()).unwrap_err();

        assert!(
            error.to_string().contains("clashes with the dependency"),
            "{error}"
        );
    }
}
